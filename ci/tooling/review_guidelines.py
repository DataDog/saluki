#!/usr/bin/env python3
"""Generate the code review guideline files from marked sections of the developer docs.

The AI review workflow reads only `codereview_guideline.md` files, so each one must be self-contained. Their text lives
in `docs/development/` between `<!-- review:NAME -->` and `<!-- /review -->` markers. The manifest,
`review_guidelines.yaml`, says which regions go into which file, in which order, and under which headings.

Usage:
    review_guidelines.py generate   # Write every guideline file
    review_guidelines.py check      # Fail if a guideline file is out of date
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import textwrap
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

try:
    import yaml
except ImportError:
    sys.exit("error: PyYAML is missing. Run `make ensure-python-venv`, or install the packages in requirements.txt.")


SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_REPO_ROOT = SCRIPT_DIR.parent.parent
DEFAULT_MANIFEST = SCRIPT_DIR / "review_guidelines.yaml"
DOCS_DIR = Path("docs/development")
GUIDELINE_NAME = "codereview_guideline.md"
HEADER = (
    "<!-- Generated by ci/tooling/review_guidelines.py from docs/development. Don't edit this file: edit the marked "
    "sections in docs/development, then run `make generate-review-guidelines`. -->"
)

MANIFEST_KEYS = {"files", "ignore_names"}
FILE_KEYS = {"path", "title", "sections"}
SECTION_KEYS = {"region", "level", "heading"}

OPEN_MARKER_RE = re.compile(r"^<!--\s*review:([a-z0-9][a-z0-9-]*)\s*-->\s*$")
CLOSE_MARKER_RE = re.compile(r"^<!--\s*/review\s*-->\s*$")
ANY_MARKER_RE = re.compile(r"<!--\s*/?review\b")
ATX_HEADING_RE = re.compile(r"^ {0,3}(#{1,6})(?:[ \t]+(.*?))?(?:[ \t]+#+)?[ \t]*$")
SETEXT_UNDERLINE_RE = re.compile(r"^ {0,3}(=+|-+)[ \t]*$")
# A fence opens with three or more backticks or tildes. A backtick fence's info string can't contain a backtick, so a
# line that starts with inline code such as ``` ``x`` ``` doesn't open one.
FENCE_RE = re.compile(r"^ {0,3}(`{3,}(?=[^`]*$)|~{3,})(.*)$")
# A code span: a run of backticks, its content, and a closing run of the same length. It can wrap lines, but not
# across a blank line.
CODE_SPAN_RE = re.compile(r"(?<!`)(`+)(?!`)((?:(?!\n[ \t]*\n).)+?)(?<!`)\1(?!`)", re.DOTALL)
# An inline link or image. The label can hold code spans and one level of brackets, and the target can have a title.
LINK_RE = re.compile(
    r"(?<!\\)(!?)\[((?:[^\[\]`\\]|\\.|`[^`]*`|\[[^\[\]]*\])+)\]"
    r"\(\s*<?((?:[^()\s<>]|\([^()\s]*\))+)>?(?:\s+(?:\"[^\"]*\"|'[^']*'|\([^)]*\)))?\s*\)"
)
REFERENCE_LINK_RE = re.compile(r"(?<!\\)\[[^\[\]]+\]\[[^\[\]]*\]|^ {0,3}\[[^\[\]]+\]:\s", re.MULTILINE)
ABSOLUTE_TARGET_RE = re.compile(r"^(https?:|mailto:)")
# A path suffix that names a line (`file.rs:10`, `file.rs:10-20`) or an anchor (`page.md#section`).
PATH_SUFFIX_RE = re.compile(r"(:\d+(-\d+)?|#[\w-]*)$")
# Backticked text that names a Rust item: `Type`, `Type::method`, or `module::function()`.
RUST_PATH_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*(?:::[A-Za-z_][A-Za-z0-9_]*)+$")
CAMEL_CASE_RE = re.compile(r"^[A-Z][a-z0-9]+(?:[A-Z][a-z0-9]*)+$")
SKIPPED_DIRS = {".git", "target", "node_modules", ".venv"}
# Git variables that would point git at another repository than `--repo-root`.
GIT_REDIRECT_VARIABLES = ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE", "GIT_COMMON_DIR")


class GuidelineError(Exception):
    """An error in the docs markers or the manifest that stops generation."""


@dataclass
class Region:
    """A marked region of a docs page."""

    page: str
    name: str
    body: str
    heading: str | None
    line: int

    @property
    def key(self) -> str:
        return f"{self.page}#{self.name}"


def split_lines(text: str) -> list[str]:
    """Split text into lines on `\\n` only, after removing a byte order mark and carriage returns."""
    return text.removeprefix("﻿").replace("\r\n", "\n").split("\n")


def fence_closes(line: str, fence: str) -> bool:
    """Return whether `line` closes a fence that `fence` opened."""
    match = FENCE_RE.match(line)
    return bool(match) and match.group(1)[0] == fence[0] and len(match.group(1)) >= len(fence) and not match.group(2).strip()


def prose_chunks(text: str) -> list[tuple[bool, str]]:
    """Split text into `(is_fenced_code, chunk)` pairs, so that link and path handling can skip code blocks."""
    chunks: list[tuple[bool, list[str]]] = []
    fence: str | None = None
    for line in text.split("\n"):
        if fence is None:
            match = FENCE_RE.match(line)
            if match:
                fence = match.group(1)
                chunks.append((True, [line]))
                continue
            if not chunks or chunks[-1][0]:
                chunks.append((False, []))
            chunks[-1][1].append(line)
        else:
            chunks[-1][1].append(line)
            if fence_closes(line, fence):
                fence = None
    return [(is_code, "\n".join(lines)) for is_code, lines in chunks]


def parse_regions(page: str, text: str) -> list[Region]:
    """Return the marked regions of one docs page.

    Markers must start at the beginning of their own line. Markers inside fenced code blocks are ignored, so that docs
    can show them as examples. Regions can't nest, and can't contain headings: the manifest sets the headings of the
    generated file.
    """
    regions: list[Region] = []
    names: set[str] = set()
    errors: list[str] = []
    heading: str | None = None
    open_name: str | None = None
    open_line = 0
    body: list[str] = []
    fence: str | None = None
    fence_line = 0
    previous = ""

    for number, line in enumerate(split_lines(text), start=1):
        location = f"{page}:{number}"
        if fence is not None:
            if fence_closes(line, fence):
                fence = None
            if open_name is not None:
                body.append(line)
            previous = ""
            continue
        fence_match = FENCE_RE.match(line)
        if fence_match:
            fence = fence_match.group(1)
            fence_line = number
            if open_name is not None:
                body.append(line)
            previous = ""
            continue

        stripped = line.strip()
        open_match = OPEN_MARKER_RE.match(stripped)
        close_match = CLOSE_MARKER_RE.match(stripped)
        if (open_match or close_match) and line != line.lstrip():
            errors.append(f"{location}: review markers must start at the beginning of the line")
            continue
        if open_match:
            if open_name is not None:
                errors.append(f"{location}: region `{open_match.group(1)}` starts inside region `{open_name}`")
                continue
            open_name = open_match.group(1)
            open_line = number
            body = []
            if open_name in names:
                errors.append(f"{location}: region `{open_name}` is defined more than once")
            names.add(open_name)
            previous = ""
            continue
        if close_match:
            if open_name is None:
                errors.append(f"{location}: `<!-- /review -->` has no matching start marker")
                continue
            regions.append(Region(page, open_name, textwrap.dedent("\n".join(body)).strip("\n"), heading, open_line))
            open_name = None
            previous = ""
            continue
        if ANY_MARKER_RE.search(CODE_SPAN_RE.sub("", line)):
            errors.append(f"{location}: review markers must be on their own line, as `<!-- review:NAME -->`")
            continue

        atx = ATX_HEADING_RE.match(line)
        setext = SETEXT_UNDERLINE_RE.match(line) and previous.strip() and not ATX_HEADING_RE.match(previous)
        if atx or setext:
            if open_name is not None:
                errors.append(f"{location}: region `{open_name}` contains a heading; set headings in the manifest")
            heading = (atx.group(2) or "") if atx else previous.strip()
        if open_name is not None:
            body.append(line)
        previous = line

    if fence is not None:
        errors.append(f"{page}:{fence_line}: this code fence has no closing fence")
    if open_name is not None:
        errors.append(f"{page}:{open_line}: region `{open_name}` has no `<!-- /review -->` end marker")
    if errors:
        raise GuidelineError("\n".join(errors))
    for region in regions:
        if not region.body.strip():
            raise GuidelineError(f"{page}:{region.line}: region `{region.name}` is empty")
    return regions


def strip_relative_links(text: str, where: str = "") -> str:
    """Replace each Markdown link to a relative target with its link text.

    Fenced code blocks and code spans don't change. A relative image or a reference-style link can't work in a
    generated file, so it is an error.
    """
    output = []
    for is_code, chunk in prose_chunks(text):
        if is_code:
            output.append(chunk)
            continue
        spans = [(span.start(), span.end()) for span in CODE_SPAN_RE.finditer(chunk)]

        def in_span(position: int) -> bool:
            return any(start <= position < end for start, end in spans)

        for reference in REFERENCE_LINK_RE.finditer(chunk):
            if not in_span(reference.start()):
                raise GuidelineError(f"{where}reference-style link `{reference.group(0).strip()}`: use an inline link")

        def replace_link(match: re.Match) -> str:
            image, label, target = match.groups()
            if in_span(match.start()) or ABSOLUTE_TARGET_RE.match(target):
                return match.group(0)
            if image:
                raise GuidelineError(f"{where}relative image `{target}` can't work in a generated guideline file")
            return label

        output.append(LINK_RE.sub(replace_link, chunk))
    return "\n".join(output)


def backticked(text: str) -> set[str]:
    """Return the text of every single-backtick code span outside fenced code blocks."""
    tokens = set()
    for is_code, chunk in prose_chunks(text):
        if not is_code:
            for span in CODE_SPAN_RE.finditer(chunk):
                if span.group(1) == "`":
                    tokens.add(" ".join(span.group(2).split()))
    return tokens


def load_regions(repo_root: Path) -> dict[str, Region]:
    """Return every region in the docs pages, keyed by `page.md#name`."""
    regions: dict[str, Region] = {}
    for path in sorted((repo_root / DOCS_DIR).glob("*.md")):
        for region in parse_regions(path.name, path.read_text(encoding="utf-8")):
            regions[region.key] = region
    return regions


def check_keys(where: str, value: object, allowed: set[str], required: set[str]) -> dict:
    """Check that a manifest entry is a mapping with known keys."""
    if not isinstance(value, dict):
        raise GuidelineError(f"{where}: expected a mapping, found `{value!r}`")
    unknown = sorted(set(value) - allowed)
    if unknown:
        raise GuidelineError(f"{where}: unknown key(s) {', '.join(unknown)}; expected {', '.join(sorted(allowed))}")
    missing = sorted(required - set(value))
    if missing:
        raise GuidelineError(f"{where}: missing key(s) {', '.join(missing)}")
    return value


def load_manifest(path: Path) -> dict:
    """Return the manifest, after checking its structure."""
    data = check_keys(str(path), yaml.safe_load(path.read_text(encoding="utf-8")), MANIFEST_KEYS, {"files"})
    if not isinstance(data["files"], list):
        raise GuidelineError(f"{path}: `files` must be a list")
    if not isinstance(data.get("ignore_names", []), list):
        raise GuidelineError(f"{path}: `ignore_names` must be a list")
    for index, entry in enumerate(data["files"]):
        where = f"{path}: files[{index}]"
        check_keys(where, entry, FILE_KEYS, {"path", "title", "sections"})
        relative = PurePosixPath(str(entry["path"]))
        if relative.is_absolute() or ".." in relative.parts or relative.name != GUIDELINE_NAME:
            raise GuidelineError(f"{where}: `{relative}` must be a relative `{GUIDELINE_NAME}` path inside the repository")
        if not isinstance(entry["title"], str) or not entry["title"].strip():
            raise GuidelineError(f"{where}: `title` must be a non-empty string")
        if not isinstance(entry["sections"], list) or not entry["sections"]:
            raise GuidelineError(f"{where}: `sections` must be a non-empty list")
        for number, section in enumerate(entry["sections"]):
            check_keys(f"{where}.sections[{number}]", section, SECTION_KEYS, {"region"})
    return data


def render_file(entry: dict, regions: dict[str, Region]) -> str:
    """Render one guideline file from its manifest entry.

    Every file starts with its title as a `##` heading. The review action joins every file that applies in path order,
    so the root file can come before or after a scoped file, and each one needs a heading of its own.
    """
    path = entry["path"]
    blocks = [HEADER, f"## {entry['title']}"]
    seen: set[str] = set()
    for section in entry["sections"]:
        key = section["region"]
        if key not in regions:
            raise GuidelineError(f"{path}: region `{key}` doesn't exist in {DOCS_DIR}")
        if key in seen:
            raise GuidelineError(f"{path}: region `{key}` is used more than once")
        seen.add(key)
        region = regions[key]
        level = section.get("level")
        where = f"{region.page}:{region.line}: "
        if level is not None:
            if level not in (2, 3, 4):
                raise GuidelineError(f"{path}: region `{key}` has heading level {level!r}; use 2, 3, or 4")
            heading = section.get("heading") or region.heading
            if not heading:
                raise GuidelineError(f"{path}: region `{key}` has no docs heading above it; set `heading`")
            blocks.append(f"{'#' * level} {strip_relative_links(heading, where)}")
        elif section.get("heading"):
            raise GuidelineError(f"{path}: region `{key}` sets `heading` without `level`")
        blocks.append(strip_relative_links(region.body, where))
    return "\n\n".join(blocks) + "\n"


def render_all(repo_root: Path, manifest: dict) -> dict[Path, str]:
    """Render every guideline file in the manifest, and check the manifest against the docs."""
    regions = load_regions(repo_root)
    rendered: dict[Path, str] = {}
    used: set[str] = set()
    for entry in manifest["files"]:
        path = Path(entry["path"])
        if path in rendered:
            raise GuidelineError(f"manifest: `{path}` is listed more than once")
        if not (repo_root / path).parent.is_dir():
            raise GuidelineError(f"manifest: directory `{path.parent}` doesn't exist")
        rendered[path] = render_file(entry, regions)
        used.update(section["region"] for section in entry["sections"])

    unused = sorted(set(regions) - used)
    if unused:
        raise GuidelineError("Regions that no guideline file uses:\n" + "\n".join(f"  {key}" for key in unused))
    return rendered


def git(repo_root: Path, *arguments: str) -> subprocess.CompletedProcess:
    """Run git in `repo_root`, ignoring variables that would point it at another repository."""
    environment = {key: value for key, value in os.environ.items() if key not in GIT_REDIRECT_VARIABLES}
    return subprocess.run(["git", *arguments], cwd=repo_root, env=environment, capture_output=True, text=True)


def repository_files(repo_root: Path) -> set[str]:
    """Return every file that git tracks or would track, relative to the repository root.

    Outside a git repository, walk the directory tree instead, and skip nested repositories and worktrees.
    """
    try:
        result = git(repo_root, "ls-files", "-z", "--cached", "--others", "--exclude-standard")
    except OSError:
        result = None
    if result is not None and result.returncode == 0:
        return {name for name in result.stdout.split("\0") if name and (repo_root / name).exists()}

    print("notice: git can't list the repository files, so the directory tree is walked instead", file=sys.stderr)
    found = set()
    for directory, subdirectories, files in os.walk(repo_root):
        here = Path(directory)
        subdirectories[:] = [
            name for name in subdirectories if name not in SKIPPED_DIRS and not (here / name / ".git").exists()
        ]
        found.update((here / name).relative_to(repo_root).as_posix() for name in files)
    return found


def with_directories(files: set[str]) -> set[str]:
    """Return the files and every directory that contains one of them."""
    paths = set(files)
    for name in files:
        parent = PurePosixPath(name).parent
        while str(parent) != ".":
            paths.add(str(parent))
            parent = parent.parent
    return paths


def find_missing_paths(rendered: dict[Path, str], files: set[str]) -> list[str]:
    """Return an error for each backticked path that doesn't exist.

    A token is a path when it contains `/` and its first part is an entry at the repository root, or, in a scoped
    file, an entry in that file's directory. Other tokens, such as `tokio::sync` or `i/o`, aren't checked.
    """
    paths = with_directories(files)
    top_level = {path for path in paths if "/" not in path}
    errors = []
    for guideline, content in sorted(rendered.items()):
        directory = PurePosixPath(guideline.as_posix()).parent.as_posix()
        for token in sorted(backticked(content)):
            token = PATH_SUFFIX_RE.sub("", token.rstrip(".,;")).rstrip("/")
            if "/" not in token or token.startswith("/") or ".." in token:
                continue
            if any(char in token for char in "*?<>{}[] …$"):
                continue
            first = token.split("/", 1)[0]
            if first in top_level:
                candidate = token
            elif directory != "." and f"{directory}/{first}" in paths:
                candidate = f"{directory}/{token}"
            else:
                continue
            if candidate not in paths:
                errors.append(f"{guideline}: `{token}` doesn't exist in the repository")
    return errors


def find_unknown_names(repo_root: Path, rendered: dict[Path, str], ignored: set[str]) -> list[str]:
    """Return a warning for each backticked Rust name that `git grep` can't find under `lib/` or `bin/`."""
    names: dict[str, set[Path]] = {}
    for path, content in rendered.items():
        for token in backticked(content):
            token = re.sub(r"<.*>$", "", token.removesuffix("()"))
            if RUST_PATH_RE.match(token) or CAMEL_CASE_RE.match(token):
                name = token.rsplit("::", 1)[-1]
                if name not in ignored:
                    names.setdefault(name, set()).add(path)
    if not names:
        return []
    # Search code only: the generated guideline files under `lib/` hold every name that they mention.
    arguments = ["grep", "--untracked", "-h", "-o", "-w", "-F"]
    for name in sorted(names):
        arguments.extend(["-e", name])
    arguments.extend(["--", "lib", "bin", ":(exclude)*.md"])
    try:
        result = git(repo_root, *arguments)
    except OSError:
        result = None
    if result is None or result.returncode not in (0, 1):
        print("notice: git grep failed, so Rust names in the guidelines weren't checked", file=sys.stderr)
        return []
    found = set(result.stdout.split())
    return [
        f"{', '.join(sorted(str(path) for path in paths))}: `{name}` doesn't appear under lib/ or bin/"
        for name, paths in sorted(names.items())
        if name not in found
    ]


def validate(repo_root: Path, rendered: dict[Path, str]) -> list[str]:
    """Return errors that apply to both commands: unlisted guideline files and missing paths."""
    files = repository_files(repo_root)
    guidelines = {Path(name) for name in files if PurePosixPath(name).name == GUIDELINE_NAME}
    errors = [
        f"{path}: this guideline file isn't in the manifest; add it there, or delete it"
        for path in sorted(guidelines - set(rendered))
    ]
    errors.extend(find_missing_paths(rendered, files | {path.as_posix() for path in rendered}))
    return errors


def generate_command(arguments: argparse.Namespace) -> int:
    """Write every guideline file that changed."""
    manifest = load_manifest(arguments.manifest)
    rendered = render_all(arguments.repo_root, manifest)
    errors = validate(arguments.repo_root, rendered)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    for path, content in sorted(rendered.items()):
        target = arguments.repo_root / path
        data = content.encode("utf-8")
        if not target.exists() or target.read_bytes() != data:
            target.write_bytes(data)
            print(f"[*] Wrote {path}")
    return 0


def check_command(arguments: argparse.Namespace) -> int:
    """Fail if a guideline file differs from what `generate` would write."""
    manifest = load_manifest(arguments.manifest)
    rendered = render_all(arguments.repo_root, manifest)
    errors = validate(arguments.repo_root, rendered)
    for path, content in sorted(rendered.items()):
        target = arguments.repo_root / path
        if not target.exists():
            errors.append(f"{path}: missing")
        elif target.read_bytes() != content.encode("utf-8"):
            errors.append(f"{path}: out of date")
    for warning in find_unknown_names(arguments.repo_root, rendered, set(manifest.get("ignore_names", []))):
        print(f"warning: {warning}", file=sys.stderr)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        print("Run `make generate-review-guidelines` and commit the result.", file=sys.stderr)
        return 1
    return 0


def parse_arguments() -> argparse.Namespace:
    """Parse the command line."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--repo-root", type=Path, default=DEFAULT_REPO_ROOT)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    subcommands = parser.add_subparsers(dest="command", required=True)
    subcommands.add_parser("generate", help="Write every guideline file").set_defaults(handler=generate_command)
    subcommands.add_parser("check", help="Fail if a guideline file is out of date").set_defaults(handler=check_command)
    return parser.parse_args()


def main() -> int:
    """Run the requested command."""
    arguments = parse_arguments()
    try:
        return arguments.handler(arguments)
    except GuidelineError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
