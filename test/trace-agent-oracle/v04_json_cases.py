def main():
    if sys.argv[1:] == ["cases"]:
        oracle = []
        for case in cases:
            entry = {"name": case["name"], "content_type": "application/json" if case["format"] == "json" else "text/plain"}
            for key in ("body", "body_b64"):
                if key in case:
                    entry[key] = case[key]
            oracle.append(entry)
        json.dump(oracle, sys.stdout)
    elif len(sys.argv) == 3 and sys.argv[1] == "fixture":
        with open(sys.argv[2]) as f:
            results = {result["name"]: result for result in json.load(f)}
        for case in cases:
            result = results[case["name"]]
            if "error" in result:
                case["expected"] = {"error": {"tag": result["error"]["tag"], "reason": result["error"]["reason"]}}
            else:
                case["expected"] = {"payload": result["payload"]}
        fixture = {"format": "datadog-trace-v0.4-json", "description": DESCRIPTION, "cases": cases}
        sys.stdout.write(json.dumps(fixture, indent=1, ensure_ascii=False) + "\n")
    else:
        sys.exit(__doc__)


