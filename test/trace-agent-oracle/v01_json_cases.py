#!/usr/bin/env python3
"""Cases for testdata/v01_json_cases.json, the v0.1 JSON decoder fixtures.

    v01_json_cases.py cases              writes the oracle input (one case per body) to stdout
    v01_json_cases.py fixture OUT.json   reads the oracle output and writes the fixture to stdout

Run through regenerate.sh rather than by hand. Every case is decoded with decode_v01_json: the trace-agent decodes a
v0.1 body as JSON whatever its media type, so `format` only says which Content-Type the oracle sent, `json` for
application/json and `any` for text/plain. The JSON value decoding itself is shared with v0.4 and covered by
v04_json_cases.py; these cases cover what v0.1 adds, the `[]Span` top level and traceChunksFromSpans.
"""

import json
import sys

DESCRIPTION = (
    "Fixtures for the v0.1 JSON span decoder. Each case's expected value is what the trace-agent's receiver decodes "
    "from the body: decodeConvertedTracerPayload on /v0.1/spans with Content-Type application/json (format json) or "
    "text/plain (format any), with no tracer headers and no container. traceChunksFromSpans builds the chunks from a "
    "map, so their order is random: they are listed here sorted, and compared in any order. Spans keep their order within a chunk; attribute maps "
    "are unordered. Cases never promote different payload fields from two chunks, since which chunk wins depends on "
    "that order. Doubles are Go's shortest formatting of the float64. Errors are classified as httpDecodingError tags "
    "them (tag) and as handleTracesV1 counts the dropped traces (reason). Generated by "
    "test/trace-agent-oracle/regenerate.sh; don't edit by hand."
)

cases = []


def c(name, body, fmt="json"):
    cases.append({"name": name, "format": fmt, "body": body})


# --- top level
c("empty_list", "[]")
c("top_level_null", "null")
c("top_level_object", "{}")
c("top_level_string", '"x"')
c("top_level_number", "1")
c("list_of_traces_is_a_type_error", '[[{"trace_id":1}]]')
c("number_in_span_list", "[1]")
c("only_nil_spans", "[null,null]")
c("empty_body", "")
c("whitespace_body", " \n ")
c("truncated_list", '[{"trace_id":1}')
c("truncated_span", '[{"trace_id":1')
c("syntax_error", "] invalid json")
c("trailing_garbage_ignored", '[{"trace_id":1}] garbage {')
c("type_error", '[{"trace_id":"1"}]')
c("type_error_before_truncation", '[{"trace_id":"1"},{"trace_id":2')
# --- traceChunksFromSpans
c("one_span", '[{"service":"s","name":"n","resource":"r","trace_id":1,"span_id":2,"start":3,"duration":4}]')
c("spans_grouped_by_trace_id", '[{"trace_id":1,"span_id":1},{"trace_id":2,"span_id":2},{"trace_id":1,"span_id":3},{"trace_id":3,"span_id":4},{"trace_id":2,"span_id":5},{"trace_id":1,"span_id":6}]')
c("nil_spans_skipped", '[null,{"trace_id":1,"span_id":1},null,{"trace_id":1,"span_id":2},null]')
c("missing_and_zero_trace_ids_group_together", '[{"span_id":1},{"trace_id":0,"span_id":2},{"trace_id":null,"span_id":3}]')
c("trace_ids_at_their_limits", '[{"trace_id":18446744073709551615,"span_id":1},{"trace_id":9223372036854775808,"span_id":2},{"trace_id":18446744073709551615,"span_id":3}]')
c("empty_spans", "[{},{},{}]")
c("duplicate_trace_id_key_last_wins", '[{"trace_id":1,"trace_id":2,"span_id":1},{"trace_id":2,"span_id":2}]')
c("many_traces", "[" + ",".join('{"trace_id":%d,"span_id":%d}' % (i % 7 + 1, i) for i in range(40)) + "]")
c("high_bits_from_each_chunk_s_first_span", '[{"trace_id":1,"span_id":1,"meta":{"_dd.p.tid":"00000000000000aa"}},{"trace_id":2,"span_id":2},{"trace_id":1,"span_id":3,"meta":{"_dd.p.tid":"bb"}},{"trace_id":2,"span_id":4,"meta":{"_dd.p.tid":"cc"}}]')
c("priority_per_chunk", '[{"trace_id":1,"span_id":1,"parent_id":5,"metrics":{"_sampling_priority_v1":1}},{"trace_id":2,"span_id":2,"metrics":{"_sampling_priority_v1":-1}},{"trace_id":1,"span_id":3,"parent_id":0,"metrics":{"_sampling_priority_v1":2}},{"trace_id":3,"span_id":4}]')
