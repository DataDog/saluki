# A body that isn't JSON, which a v0.4 endpoint would retry as MessagePack under this media type.
c("any_media_type_msgpack_like_body", "\x91\x81\xa7service\xa2mp", "any")
c("any_media_type_truncated", '[{"trace_id":1', "any")


def main():
    if sys.argv[1:] == ["cases"]:
        oracle = []
        for case in cases:
            content_type = "application/json" if case["format"] == "json" else "text/plain"
            oracle.append({"name": case["name"], "content_type": content_type, "body": case["body"], "version": "v0.1"})
        json.dump(oracle, sys.stdout)
    elif len(sys.argv) == 3 and sys.argv[1] == "fixture":
        results = {result["name"]: result for result in json.load(open(sys.argv[2]))}
        for case in cases:
            result = results[case["name"]]
            if "error" in result:
                case["expected"] = {"error": {"tag": result["error"]["tag"], "reason": result["error"]["reason"]}}
            else:
                payload = result["payload"]
                # The oracle's chunk order is random: sorted, the fixture only changes when the payload does.
                payload["chunks"].sort(key=lambda chunk: json.dumps(chunk, sort_keys=True))
                case["expected"] = {"payload": payload}
        fixture = {"format": "datadog-trace-v0.1-json", "description": DESCRIPTION, "cases": cases}
        sys.stdout.write(json.dumps(fixture, indent=1, ensure_ascii=False) + "\n")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
