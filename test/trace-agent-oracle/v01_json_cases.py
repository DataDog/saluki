c("payload_fields_from_one_chunk", '[{"trace_id":1,"span_id":1,"meta":{"env":"e1","version":"v1","_dd.hostname":"h1","_dd.git.commit.sha":"sha1","_dd.apm_mode":"m1"}},{"trace_id":2,"span_id":2},{"trace_id":1,"span_id":3,"meta":{"env":"e2","_dd.hostname":"h2"}}]')
