# --- a minimal MessagePack encoder, as the script runs without packages
class U64(int):
    """An unsigned integer written with the uint64 marker."""


class I64(int):
    """A signed integer written with the int64 marker."""


class F32(float):
    """A float written with the float32 marker."""


class Raw(bytes):
    """Bytes written as they are."""


class Map(list):
    """A map, as a list of (key, value) pairs, so that keys may repeat."""


def header(n, fix, fix_max, m16, m32):
    if n <= fix_max:
        return bytes([fix | n])
    if n <= 0xFFFF:
        return bytes([m16]) + struct.pack(">H", n)
    return bytes([m32]) + struct.pack(">I", n)


def enc(v):
    if isinstance(v, Raw):
        return bytes(v)
    if v is None:
        return b"\xc0"
    if v is True:
        return b"\xc3"
    if v is False:
        return b"\xc2"
    if isinstance(v, U64):
        return b"\xcf" + struct.pack(">Q", v)
    if isinstance(v, I64):
        return b"\xd3" + struct.pack(">q", v)
    if isinstance(v, int):
        if 0 <= v <= 0x7F:
            return bytes([v])
        if -32 <= v < 0:
            return struct.pack(">b", v)
        if v >= 0:
            for marker, fmt, top in ((0xCC, ">B", 0xFF), (0xCD, ">H", 0xFFFF), (0xCE, ">I", 0xFFFFFFFF)):
                if v <= top:
                    return bytes([marker]) + struct.pack(fmt, v)
            return b"\xcf" + struct.pack(">Q", v)
        for marker, fmt, low in ((0xD0, ">b", -0x80), (0xD1, ">h", -0x8000), (0xD2, ">i", -0x80000000)):
            if v >= low:
                return bytes([marker]) + struct.pack(fmt, v)
        return b"\xd3" + struct.pack(">q", v)
    if isinstance(v, F32):
        return b"\xca" + struct.pack(">f", v)
    if isinstance(v, float):
        return b"\xcb" + struct.pack(">d", v)
    if isinstance(v, str):
        b = v.encode("utf-8", "surrogateescape")
        if len(b) < 32:
            return bytes([0xA0 | len(b)]) + b
        return (b"\xd9" + bytes([len(b)]) if len(b) < 256 else b"\xda" + struct.pack(">H", len(b))) + b
    if isinstance(v, bytes):
        return b"\xc4" + bytes([len(v)]) + v
    if isinstance(v, Map):
        return header(len(v), 0x80, 15, 0xDE, 0xDF) + b"".join(enc(k) + enc(x) for k, x in v)
    if isinstance(v, dict):
        return enc(Map(v.items()))
    if isinstance(v, (list, tuple)):
        return header(len(v), 0x90, 15, 0xDC, 0xDD) + b"".join(enc(x) for x in v)
    raise TypeError(v)



class Bin(bytes):
    """Bytes written as bin8."""


def strbin(s):
    """A string written as bin8."""
    return Bin(s.encode())


def raw_str(b):
    """Raw bytes written with a str marker, which may not be valid UTF-8."""
    return Raw(bytes([0xA0 | len(b)]) + b)


def array32(items):
    return Raw(b"\xdd" + struct.pack(">I", len(items)) + b"".join(enc(x) for x in items))


def map16_count(n):
    return Raw(b"\xde" + struct.pack(">H", n))


def array_count(n):
    return Raw(b"\xdd" + struct.pack(">I", n))


