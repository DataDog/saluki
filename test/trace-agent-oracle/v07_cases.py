def span(**fields):
    s = {"service": "svc", "name": "op", "resource": "res", "trace_id": 1, "span_id": 2, "parent_id": 0,
         "start": 100, "duration": 200}
    s.update(fields)
    return Map((k, v) for k, v in s.items() if v is not OMIT)


OMIT = object()


def chunk(*spans, **fields):
    ch = Map(fields.items())
    ch.append(("spans", list(spans)))
    return ch


def tp(*chunks, **fields):
    p = Map(fields.items())
    p.append(("chunks", list(chunks)))
    return p


def av(type_=OMIT, **fields):
    """An AttributeAnyValue (or AttributeArrayValue) map."""
    m = Map() if type_ is OMIT else Map([("type", type_)])
    m.extend(fields.items())
    return m


def arr(*values):
    """An AttributeArray map."""
    return Map([("values", list(values))])


def event(attributes=OMIT, **fields):
    m = Map(fields.items())
    if attributes is not OMIT:
        m.append(("attributes", attributes))
    return m


def link(**fields):
    return Map(fields.items())


def with_event(*events):
    return tp(chunk(span(span_events=list(events))))


