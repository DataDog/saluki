#!/usr/bin/env python3
"""Cases for testdata/v1_cases.json, the v1.0 MessagePack decoder fixtures from the trace-agent's own decoder.

    v1_cases.py cases              writes the oracle input (one case per body) to stdout
    v1_cases.py fixture OUT.json   reads the oracle output and writes the fixture to stdout

Run through regenerate.sh rather than by hand. Every case is decoded with decode_v1_payload: the trace-agent decodes a
v1.0 body as an InternalTracerPayload whatever its media type, so the oracle sends application/msgpack. The cases
cover the string table and streaming strings, chunk priorities, attribute values and the framing; the payloads
`testdata/v1_decoder_cases.json` holds, from the reference encoder, cover the fields at large.
"""

import base64
import json
import struct
import sys

DESCRIPTION = (
    "Fixtures for the v1.0 MessagePack trace decoder. Each case's expected value is what the trace-agent's receiver "
    "decodes from the body: decodeConvertedTracerPayload on /v1.0/traces (InternalTracerPayload.UnmarshalMsg), with no "
    "tracer headers and no container. A payload lists its chunks and spans in order; attribute maps are unordered. "
    "Doubles are Go's shortest formatting of the float64. Errors are classified as httpDecodingError tags them (tag) "
    "and as handleTracesV1 counts the dropped traces (reason). Generated by test/trace-agent-oracle/regenerate.sh; "
    "don't edit by hand."
)


# --- a minimal MessagePack encoder, as the script runs without packages
class U64(int):
    """An unsigned integer written with the uint64 marker."""


class I64(int):
    """A signed integer written with the int64 marker."""


class F32(float):
    """A float written with the float32 marker."""


class Raw(bytes):
    """Bytes written as they are."""


class Map(list):
    """A map, as a list of (key, value) pairs, so that keys may repeat."""


def header(n, fix, fix_max, m16, m32):
    if n <= fix_max:
        return bytes([fix | n])
    if n <= 0xFFFF:
        return bytes([m16]) + struct.pack(">H", n)
    return bytes([m32]) + struct.pack(">I", n)


def enc(v):
    if isinstance(v, Raw):
        return bytes(v)
    if v is None:
        return b"\xc0"
    if v is True:
        return b"\xc3"
    if v is False:
        return b"\xc2"
    if isinstance(v, U64):
        return b"\xcf" + struct.pack(">Q", v)
    if isinstance(v, I64):
        return b"\xd3" + struct.pack(">q", v)
    if isinstance(v, int):
        if 0 <= v <= 0x7F:
            return bytes([v])
        if -32 <= v < 0:
            return struct.pack(">b", v)
        if v >= 0:
            for marker, fmt, top in ((0xCC, ">B", 0xFF), (0xCD, ">H", 0xFFFF), (0xCE, ">I", 0xFFFFFFFF)):
                if v <= top:
                    return bytes([marker]) + struct.pack(fmt, v)
            return b"\xcf" + struct.pack(">Q", v)
        for marker, fmt, low in ((0xD0, ">b", -0x80), (0xD1, ">h", -0x8000), (0xD2, ">i", -0x80000000)):
            if v >= low:
                return bytes([marker]) + struct.pack(fmt, v)
        return b"\xd3" + struct.pack(">q", v)
    if isinstance(v, F32):
        return b"\xca" + struct.pack(">f", v)
    if isinstance(v, float):
        return b"\xcb" + struct.pack(">d", v)
    if isinstance(v, str):
        b = v.encode("utf-8", "surrogateescape")
        if len(b) < 32:
            return bytes([0xA0 | len(b)]) + b
        return (b"\xd9" + bytes([len(b)]) if len(b) < 256 else b"\xda" + struct.pack(">H", len(b))) + b
    if isinstance(v, bytes):
        return b"\xc4" + bytes([len(v)]) + v
    if isinstance(v, Map):
        return header(len(v), 0x80, 15, 0xDE, 0xDF) + b"".join(enc(k) + enc(x) for k, x in v)
    if isinstance(v, dict):
        return enc(Map(v.items()))
    if isinstance(v, (list, tuple)):
        return header(len(v), 0x90, 15, 0xDC, 0xDD) + b"".join(enc(x) for x in v)
    raise TypeError(v)


class Strs(list):
    """A string table: each entry written as a MessagePack string, even as raw bytes."""


def s(text):
    """A streaming string literal, from text or from raw bytes."""
    b = text if isinstance(text, bytes) else text.encode()
    return Raw(header(len(b), 0xA0, 31, 0xD9, 0xD9) + b if len(b) < 256 else b"\xda" + struct.pack(">H", len(b)) + b)


TRACE_ID = bytes(range(1, 17))
RESOURCE = s("GET /checkout/cart")


def span(service=s("svc"), name=s("op"), span_id=U64(7), extra=()):
    """A span, its resource long enough for the decoder's size bounds."""
    return Map([(1, service), (2, name), (3, RESOURCE), (4, span_id)] + list(extra))


def chunk(spans, priority=None, extra=()):
    fields = [] if priority is None else [(1, priority)]
    return Map(fields + [(6, TRACE_ID), (4, spans)] + list(extra))


def payload(chunks, table=None, extra=()):
    fields = [] if table is None else [(1, Raw(header(len(table), 0x90, 15, 0xDC, 0xDD) + b"".join(s(t) for t in table)))]
    return enc(Map(fields + list(extra) + [(11, chunks)]))


def attrs(*entries):
    """An attribute map: a flat array of key, type and value."""
    return [x for entry in entries for x in entry]


cases = []


def c(name, body):
    cases.append({"name": name, "body_b64": base64.b64encode(body).decode()})


# --- the string table and streaming strings
c("table_entries_resolve", payload([chunk([span(1, 2)])], table=["svc", "op"]))
c("table_duplicates_each_take_an_index", payload([chunk([span(3, 2)])], table=["a", "a", "b"]))
c("table_empty_entries_take_no_index", payload([chunk([span(2, 1)])], table=["", "a", "", "b"]))
c("table_out_of_range_ref", payload([chunk([span(4, 1)])], table=["a", "a", "b"]))
c("literal_after_table_duplicates_takes_the_last", payload([chunk([span(s("a"), 2), span(s("c"), 4, U64(8))])],
                                                      table=["a", "a", "b"]))
c("repeated_literal_takes_no_index", payload([chunk([span(s("a"), s("a")), span(s("b"), 2, U64(8))])]))
c("empty_literal_takes_no_index", payload([chunk([span(s(""), s("b")), span(1, 1, U64(8))])]))
c("invalid_utf8_literals_are_distinct", payload([chunk([span(s(b"a\xff"), s(b"a\xfe")), span(s("b"), 3, U64(8))])]))
c("invalid_utf8_literal_repeated", payload([chunk([span(s(b"a\xff"), s(b"a\xff")), span(s("b"), 2, U64(8))])]))
c("invalid_utf8_table_entry", payload([chunk([span(1, 2)])], table=[b"x\xff", "op"]))
c("table_after_another_field", enc(Map([(2, s("cid")), (1, Raw(b"\x91\xa1a")), (11, [chunk([span()])])])))
c("unseen_ref", payload([chunk([span(9)])]))
c("payload_fields", payload([chunk([span()])], extra=[(2, s("cid")), (3, s("python")), (4, s("3.12")),
                                                      (5, s("2.0.0")), (6, s("rt")), (7, s("prod")),
                                                      (8, s("host-1")), (9, s("1.2.3"))]))

# --- chunk priorities
c("priority_absent", payload([chunk([span()])]))
c("priority_none", payload([chunk([span()], -128)]))
c("priority_auto_drop", payload([chunk([span()], 0)]))
c("priority_user_keep", payload([chunk([span()], 2)]))
c("priority_negative", payload([chunk([span()], -1)]))
c("chunk_fields", payload([chunk([span()], 1, extra=[(2, s("synthetics")), (5, True), (7, 4)])]))

# --- attribute values
c("attribute_values", payload([chunk([span(extra=[(9, attrs(
    [s("str"), 1, s("v")], [s("bool"), 2, True], [s("dbl"), 3, 2.5], [s("f32"), 3, F32(1.5)], [s("int"), 4, -3],
    [s("bytes"), 5, b"\x00\x01"], [s("arr"), 6, [1, s("x"), 4, 2]],
    [s("kvl"), 7, [s("k"), 4, 1, s("k2"), 1, s("w")]]))])])]))
c("attribute_double_as_int", payload([chunk([span(extra=[(9, attrs([s("dbl"), 3, 2]))])])]))
c("payload_and_chunk_attributes", payload([chunk([span()], extra=[(3, attrs([s("c"), 1, s("cv")]))])],
                                          extra=[(10, attrs([s("p"), 1, s("pv")]))]))

# --- framing
c("empty_body", b"")
c("empty_payload", b"\x80")
c("outer_array", b"\x90")
c("outer_nil", b"\xc0")
c("trailing_bytes_ignored", payload([chunk([span()])]) + b"\xc1\x2a")
c("ends_where_a_string_is_due", b"\x81\x07")
c("string_cut_short", b"\x81\x07\xa5pr")
c("fields_cut_short", b"\x84\x03\xa2go")
c("map_count_over_the_remaining_bytes", b"\x8f\x03\xa2go")
c("collection_over_the_limit", b"\x81\x0b\xdd\x00\x07\xa1\x21" + b"\x00" * 8)
# A chunk's attributes, so that the chunk is large enough for the decoder's size bounds.
c("double_cut_short", b"\x81\x0b\x91\x82\x06" + enc(TRACE_ID) + b"\x03\x93\xa1d\x03\xc9")
c("field_number_not_an_int", b"\x81\xa1x\x01")
c("chunk_list_nil", b"\x81\x0b\xc0")


def main():
    if sys.argv[1:] == ["cases"]:
        oracle = [{"name": case["name"], "content_type": "application/msgpack", "body_b64": case["body_b64"],
                   "version": "v1.0"} for case in cases]
        json.dump(oracle, sys.stdout)
    elif len(sys.argv) == 3 and sys.argv[1] == "fixture":
        results = {result["name"]: result for result in json.load(open(sys.argv[2]))}
        for case in cases:
            case["format"] = "msgpack"
            result = results[case["name"]]
            if "error" in result:
                case["expected"] = {"error": {"tag": result["error"]["tag"], "reason": result["error"]["reason"]}}
            else:
                case["expected"] = {"payload": result["payload"]}
        fixture = {"format": "datadog-trace-v1.0", "description": DESCRIPTION, "cases": cases}
        sys.stdout.write(json.dumps(fixture, indent=1, ensure_ascii=False) + "\n")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
