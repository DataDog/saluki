//! Explain fixtures: golden documents for the default program, and hand-written checks of what they say.

use std::path::Path;

use serde_json::json;

use super::*;
use crate::{
    model::{Kind, KindSet, TimestampForm},
    testing::{default_program_catalog, DEFAULT_PROGRAM_JSON},
    validate::Validator,
};

/// The environment variable that makes the golden tests rewrite their files instead of comparing against them.
const UPDATE_VARIABLE: &str = "SALUKI_METRIC_PLAN_UPDATE_EXPLAIN";

fn default_program() -> Explain {
    let plan = Plan::from_json(DEFAULT_PROGRAM_JSON).unwrap();
    let registry = OperatorRegistry::native();
    let report = Validator::new(&registry, &default_program_catalog()).validate(&plan);
    Explain::of(&plan, &registry, &report)
}

fn port_type(kinds: &[Kind], timestamps: TimestampForm) -> PortType {
    PortType {
        kinds: KindSet::of(kinds),
        timestamps,
    }
}

fn node<'a>(explain: &'a Explain, id: &str) -> &'a NodeEntry {
    let id = id.parse::<NodeId>().unwrap();
    explain
        .graph
        .nodes
        .iter()
        .find(|node| node.id == id)
        .unwrap_or_else(|| panic!("no node `{}`", id))
}

#[track_caller]
fn assert_golden(file: &str, generated: &str) {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("fixtures")
        .join("explain")
        .join(file);
    if std::env::var_os(UPDATE_VARIABLE).is_some() {
        std::fs::write(&path, generated).expect("golden file is writable");
        return;
    }
    let checked_in = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        checked_in == generated,
        "The explain document at {} does not match. If you changed explain or the default-program fixture on purpose, \
         review the difference and regenerate the file with:\n\n    {}=1 cargo test -p saluki-metric-plan explain\n",
        path.display(),
        UPDATE_VARIABLE
    );
}

// The golden files are change detectors: they were generated by `Explain` and reviewed, so they show when explain's
// output changes, not that it is right. What the output says is checked against hand-derived values by the tests
// below: every node's contract summary, the port types at representative edges, the bindings, and the bounds.

#[test]
fn the_default_programs_explain_json_matches_its_golden_file() {
    assert_golden("default-program.json", &default_program().to_json().unwrap());
}

#[test]
fn the_default_programs_explain_text_matches_its_golden_file() {
    assert_golden("default-program.txt", &default_program().to_text());
}

#[test]
fn explain_is_deterministic() {
    assert_eq!(
        default_program().to_json().unwrap(),
        default_program().to_json().unwrap()
    );
    assert_eq!(default_program().to_text(), default_program().to_text());
}

#[test]
fn the_default_programs_explain_describes_its_graph() {
    let explain = default_program();
    assert_eq!(explain.explain_version, 1);
    assert!(explain.plan.valid);
    assert!(explain.findings.is_empty());

    // The fixture has 34 nodes and 34 edges.
    assert_eq!(explain.graph.nodes.len(), 34);
    assert_eq!(explain.graph.edges.len(), 34);

    let source = node(&explain, "dsd_in");
    assert_eq!(source.op.as_str(), "source");
    assert_eq!(source.boundary.as_deref(), Some("io_host"));
    assert_eq!(source.provenance, Some(Provenance::Native("dsd_in".parse().unwrap())));
    assert!(source.inputs.is_empty());
    assert_eq!(
        source.outputs[0].to.as_ref().map(ToString::to_string).as_deref(),
        Some("dsd_enrich.in")
    );

    // Aggregation runs in a host, keeps keyed state, and loses by policy (its merge), capacity, and at shutdown.
    let aggregate = node(&explain, "dsd_agg");
    assert_eq!(aggregate.loss, vec!["policy", "capacity", "shutdown"]);
    assert_eq!(aggregate.bindings.len(), 9);
    assert_eq!(aggregate.bindings[0].param, "window");
    assert_eq!(
        aggregate.bindings[0].binding.to_string(),
        "dogstatsd.aggregation.window_duration"
    );
    assert_eq!(aggregate.bindings[0].resolved, Some(json!("10s")));

    // Bindings inside predicates are listed with their place in the predicate and their resolved values.
    let blocklist = node(&explain, "dsd_prefix_filter_blocklist");
    let bindings = blocklist
        .bindings
        .iter()
        .map(|binding| {
            (
                binding.param.as_str(),
                binding.binding.to_string(),
                binding.resolved.clone(),
            )
        })
        .collect::<Vec<_>>();
    assert_eq!(
        bindings,
        vec![
            (
                "predicate.intake_name.values",
                "dogstatsd.metric_filter.values".to_string(),
                Some(json!(["tenant.raw.blocked"]))
            ),
            (
                "predicate.intake_name.prefix",
                "dogstatsd.metric_filter.match_prefix".to_string(),
                Some(json!(false))
            ),
        ]
    );
    assert_eq!(blocklist.loss, Vec::<String>::new());
    assert_eq!(node(&explain, "dsd_prefix_filter_blocklist_true").loss, vec!["policy"]);

    // Port types per edge, derived by hand: aggregation turns counters into rates and histograms into rates, gauges,
    // and distributions, all timestamped; the timestamp split's passthrough port carries timestamped points, with
    // counters as rates.
    let edge_type = |from: &str| {
        explain
            .graph
            .edges
            .iter()
            .find(|edge| edge.from.to_string() == from)
            .and_then(|edge| edge.port_type)
            .unwrap_or_else(|| panic!("no typed edge from `{}`", from))
    };
    use Kind::*;
    assert_eq!(
        edge_type("dsd_in.metrics"),
        port_type(&[Counter, Gauge, Set, Histogram, Distribution], TimestampForm::Mixed)
    );
    assert_eq!(
        edge_type("dsd_agg.out"),
        port_type(&[Rate, Gauge, Set, Distribution], TimestampForm::Timestamped)
    );
    assert_eq!(
        edge_type("dsd_no_agg_split.passthrough"),
        port_type(&[Rate, Gauge, Set, Histogram, Distribution], TimestampForm::Timestamped)
    );
    assert_eq!(
        edge_type("af_metrics_gateway.true"),
        port_type(&[Counter, Rate, Gauge, Set], TimestampForm::Mixed)
    );

    let output = explain
        .graph
        .outputs
        .iter()
        .find(|output| output.id.as_str() == "dd_metrics_encode")
        .unwrap();
    assert_eq!(output.emitted_by, vec!["metrics_policy_0".parse::<NodeId>().unwrap()]);
    assert_eq!(explain.graph.scopes.len(), 1);
    assert_eq!(explain.graph.scopes[0].name.as_str(), "post_enrich");
}

