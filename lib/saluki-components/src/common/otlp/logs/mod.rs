//! OTLP logs helpers shared between the OTLP logs path's components.

use saluki_core::data_model::event::log::Log;
use saluki_error::{generic_error, GenericError};
use serde_json::Value as JsonValue;
use stringtheory::MetaString;

/// A field of a log's content.
enum ContentField<'a> {
    String(&'a str),
    Value(&'a JsonValue),
}

/// Renders translated OTLP logs into the content of their log messages.
///
/// The content is the log as a `datadogV2.HTTPLogItem` without its `ddtags`, serialized by `HTTPLogItem.MarshalJSON`.
/// It holds:
///
/// - `hostname` and `service`, when the log has them, and `message`.
/// - Every additional property, overwriting a top-level field of the same name. A `datadog.log.source` property, and a
///   `ddtags` property from a resource attribute, stay in the content.
/// - `status`, the log's status, even when it's empty. It's set after every other property, so it overwrites a
///   `status` property.
///
/// The content is serialized with `serde_json`, with its keys sorted by their bytes, as Go sorts map keys. Its escaping
/// and number formatting differ from Go's `encoding/json` (`gap/json-encoding`): `<`, `>`, `&`, U+2028, and U+2029
/// aren't escaped, and floats use `serde_json`'s layout, such as `1.0` and `1e21` where Go writes `1` and `1e+21`.
///
/// A renderer keeps its serialization buffer between logs, so rendering many logs reuses its allocation.
#[derive(Debug, Default)]
pub struct ContentRenderer {
    buffer: Vec<u8>,
}

impl ContentRenderer {
    /// Renders a log's content.
    ///
    /// # Errors
    ///
    /// If a property can't be serialized, an error is returned, and the log should be dropped.
    pub fn render(&mut self, log: &Log) -> Result<MetaString, GenericError> {
        // The fields in the order that `HTTPLogItem.MarshalJSON` assembles them, where a later field overwrites an
        // earlier one with the same key.
        let mut fields = Vec::with_capacity(log.additional_properties().len() + 4);
        if !log.hostname().is_empty() {
            fields.push(("hostname", ContentField::String(log.hostname())));
        }
        fields.push(("message", ContentField::String(log.message())));
        if !log.service().is_empty() {
            fields.push(("service", ContentField::String(log.service())));
        }
        fields.extend(
            log.additional_properties()
                .iter()
                .map(|(key, value)| (key.as_ref(), ContentField::Value(value))),
        );
        fields.push(("status", ContentField::String(log.status())));

        // Go sorts map keys by their bytes, as `str` orders them. The sort is stable, so fields with the same key stay
        // in assembly order, and only the last of them is written.
        fields.sort_by_key(|(key, _)| *key);

        self.buffer.clear();
        self.buffer.push(b'{');
        let mut first = true;
        for (index, (key, field)) in fields.iter().enumerate() {
            if fields.get(index + 1).is_some_and(|(next, _)| next == key) {
                continue;
            }
            if !first {
                self.buffer.push(b',');
            }
            first = false;

            let buffer = &mut self.buffer;
            let written = serde_json::to_writer(&mut *buffer, key).and_then(|()| {
                buffer.push(b':');
                match field {
                    ContentField::String(value) => serde_json::to_writer(&mut *buffer, value),
                    ContentField::Value(value) => serde_json::to_writer(&mut *buffer, value),
                }
            });
            written.map_err(|e| generic_error!("Failed to serialize log property '{}': {}", key, e))?;
        }
        self.buffer.push(b'}');

        let content = simdutf8::basic::from_utf8(&self.buffer)
            .map_err(|e| generic_error!("Rendered log content isn't valid UTF-8: {}", e))?;
        Ok(MetaString::from(content))
    }
}

#[cfg(test)]
mod tests {
    use std::collections::HashMap;

    use saluki_core::data_model::event::log::Log;
    use saluki_core::data_model::tags::{Tag, TagSet};
    use serde::Deserialize;
    use serde_json::{json, Value as JsonValue};
    use stringtheory::MetaString;

    use super::ContentRenderer;

    /// Vectors generated by the Go program in `testdata/generate-render-vectors`, which documents how to regenerate
    /// them. Their content is the target.
    const RENDER_VECTORS: &str = include_str!("testdata/render_vectors.json");

    /// A render vector whose current content differs from its target, the gap that explains it, and the current
    /// content, which the test checks exactly.
    struct RenderGap {
        vector: &'static str,
        gap: &'static str,
        current: &'static str,
    }

    /// The render vectors whose current content differs from the target. Remove an entry in the change that fixes its
    /// gap.
    ///
    /// `gap/json-encoding`: Go escapes `<`, `>`, `&`, U+2028, and U+2029, and writes whole-number floats without a
    /// fraction and floats under 1e21 in decimal, where `serde_json` doesn't escape them and writes `3.0` and `1e+20`.
    const RENDER_GAPS: &[RenderGap] = &[
        RenderGap {
            vector: "html-characters",
            gap: "gap/json-encoding",
            current: "{\"<key>\":\"a & b > c\",\"message\":\"<a href=\\\"x\\\">&amp;</a>\",\"status\":\"info\"}",
        },
        RenderGap {
            vector: "line-separators",
            gap: "gap/json-encoding",
            current: "{\"message\":\"one\u{2028}two\u{2029}three\",\"status\":\"info\"}",
        },
        RenderGap {
            vector: "numbers",
            gap: "gap/json-encoding",
            current: "{\"bool\":true,\"fraction\":0.1,\"int\":1,\"int64-max\":9223372036854775807,\"int64-min\":-9223372036854775808,\"integral\":3.0,\"large\":1e+21,\"large-edge\":1e+20,\"max-float\":1.7976931348623157e+308,\"message\":\"m\",\"min-positive\":5e-324,\"negative\":-42,\"null\":null,\"small\":1e-7,\"small-edge\":1e-6,\"status\":\"info\",\"third\":0.3333333333333333,\"zero-float\":0.0}",
        },
        RenderGap {
            vector: "nested",
            gap: "gap/json-encoding",
            current: "{\"array\":[\"value1\",2,3.5,false,null],\"array_with_maps\":[{\"item_name\":\"item1\",\"value\":100},{\"item_name\":\"<item2>\",\"value\":200}],\"empty\":{},\"matrix\":[[{\"a\":0,\"b\":1}],[]],\"message\":\"m\",\"status\":\"debug\"}",
        },
    ];

    /// Decodes a property value of a render vector, where each float is written as `{"f64": "<hex bits>"}`.
    fn decode_property(value: JsonValue) -> JsonValue {
        match value {
            JsonValue::Object(object) => match object.get("f64").and_then(JsonValue::as_str) {
                Some(bits) if object.len() == 1 => {
                    let bits = u64::from_str_radix(bits, 16).expect("float bits should be hex");
                    JsonValue::from(f64::from_bits(bits))
                }
                _ => JsonValue::Object(
                    object
                        .into_iter()
                        .map(|(key, value)| (key, decode_property(value)))
                        .collect(),
                ),
            },
            JsonValue::Array(values) => JsonValue::Array(values.into_iter().map(decode_property).collect()),
            other => other,
        }
    }

    #[derive(Deserialize)]
    struct RenderVector {
        name: String,
        input: RenderInput,
        content: String,
    }

    #[derive(Deserialize)]
    struct RenderInput {
        hostname: Option<String>,
        service: Option<String>,
        message: String,
        status: String,
        properties: Option<HashMap<String, JsonValue>>,
    }

    fn log_with_properties(message: &str, properties: JsonValue) -> Log {
        let properties = match properties {
            JsonValue::Object(properties) => properties
                .into_iter()
                .map(|(key, value)| (MetaString::from(key), value))
                .collect::<HashMap<_, _>>(),
            other => panic!("properties must be a JSON object, got {}", other),
        };
        Log::new(message).with_additional_properties(properties)
    }

    #[test]
    fn matches_the_reference_byte_for_byte_except_known_gaps() {
        let vectors: Vec<RenderVector> = serde_json::from_str(RENDER_VECTORS).expect("vectors should parse");
        assert!(!vectors.is_empty());
        for gap in RENDER_GAPS {
            assert!(
                vectors.iter().any(|vector| vector.name == gap.vector),
                "render gap for {} names an unknown vector",
                gap.vector
            );
        }

        // One renderer for every vector, as the transform uses one for every log.
        let mut renderer = ContentRenderer::default();
        let mut failures = Vec::new();
        for vector in vectors {
            let input = vector.input;
            let properties = input
                .properties
                .unwrap_or_default()
                .into_iter()
                .map(|(key, value)| (MetaString::from(key), decode_property(value)))
                .collect::<HashMap<_, _>>();
            let log = Log::new(input.message)
                .with_hostname(input.hostname.map(MetaString::from))
                .with_service(input.service.map(MetaString::from))
                .with_status(input.status)
                .with_additional_properties(properties);

            let content = renderer
                .render(&log)
                .unwrap_or_else(|e| panic!("{}: render failed: {}", vector.name, e));
            let content = &*content;
            match RENDER_GAPS.iter().find(|gap| gap.vector == vector.name) {
                None if content != vector.content => failures.push(format!(
                    "{}: content differs from the target with no known gap\n  target:  {}\n  current: {}",
                    vector.name, vector.content, content
                )),
                Some(gap) if content == vector.content => failures.push(format!(
                    "{}: content now matches the target; remove its entry for {}",
                    vector.name, gap.gap
                )),
                Some(gap) if content != gap.current => failures.push(format!(
                    "{}: current content changed\n  expected: {}\n  current:  {}",
                    vector.name, gap.current, content
                )),
                _ => {}
            }
        }
        assert!(failures.is_empty(), "render vector failures:\n{}", failures.join("\n"));
    }

    #[test]
    fn properties_overwrite_top_level_fields_except_status() {
        let log = log_with_properties(
            "from body",
            json!({
                "message": "from resource",
                "hostname": "from attribute",
                "service": "from attribute",
                "status": "from resource",
                "ddtags": "from:resource",
                "datadog.log.source": "custom_source",
            }),
        )
        .with_hostname(MetaString::from_static("host-a"))
        .with_service(MetaString::from_static("svc"))
        .with_status("error");

        let content: JsonValue =
            serde_json::from_str(&ContentRenderer::default().render(&log).expect("log should render"))
                .expect("content should be JSON");
        assert_eq!(
            content,
            json!({
                "message": "from resource",
                "hostname": "from attribute",
                "service": "from attribute",
                "status": "error",
                "ddtags": "from:resource",
                "datadog.log.source": "custom_source",
            })
        );
    }

    #[test]
    fn leaves_out_empty_hostname_and_service_but_not_status() {
        let content = ContentRenderer::default()
            .render(&Log::new("m"))
            .expect("log should render");
        assert_eq!(&*content, r#"{"message":"m","status":""}"#);
    }

    #[test]
    fn leaves_the_tags_out_of_the_content() {
        let log = Log::new("m").with_tags([Tag::from_static("env:prod")].into_iter().collect::<TagSet>());
        let content = ContentRenderer::default().render(&log).expect("log should render");
        assert_eq!(&*content, r#"{"message":"m","status":""}"#);
    }

    #[test]
    fn reuses_its_buffer_without_leaking_earlier_content() {
        let mut renderer = ContentRenderer::default();
        let long = log_with_properties("first", json!({"padding": "x".repeat(1024)}));
        renderer.render(&long).expect("log should render");

        let content = renderer.render(&Log::new("second")).expect("log should render");
        assert_eq!(&*content, r#"{"message":"second","status":""}"#);
    }
}
