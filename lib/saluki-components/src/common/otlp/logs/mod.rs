//! OTLP logs helpers shared between the OTLP logs path's components.

use std::collections::BTreeMap;

use saluki_core::data_model::event::log::Log;
use saluki_error::{generic_error, GenericError};
use serde_json::Value as JsonValue;

/// A field of a log's content.
enum ContentField<'a> {
    String(&'a str),
    Value(&'a JsonValue),
}

/// Renders a translated OTLP log into its content, as the Agent's logs agent exporter does.
///
/// The Agent's translator returns a `datadogV2.HTTPLogItem`, and the exporter sends the item, without its `ddtags`, as
/// the content of the log message, serialized by `HTTPLogItem.MarshalJSON`. The content holds:
///
/// - `hostname` and `service`, when the log has them, and `message`.
/// - Every additional property, overwriting a top-level field of the same name. A `datadog.log.source` property, and a
///   `ddtags` property from a resource attribute, stay in the content.
/// - `status`, the log's status, even when it's empty. The translator sets it after every other property, so it
///   overwrites a `status` property.
///
/// The content is serialized as Go's `encoding/json` does, with sorted keys, Go's escaping, and Go's number formatting.
///
/// # Errors
///
/// If a property can't be serialized as Go serializes it, an error is returned. The Agent drops such logs.
pub fn render_content(log: &Log) -> Result<String, GenericError> {
    // Go sorts map keys by their bytes, as `BTreeMap` orders `&str` keys. Later inserts overwrite earlier ones, in the
    // order that the Agent's item assembles them.
    let mut fields = BTreeMap::new();
    if !log.hostname().is_empty() {
        fields.insert("hostname", ContentField::String(log.hostname()));
    }
    fields.insert("message", ContentField::String(log.message()));
    if !log.service().is_empty() {
        fields.insert("service", ContentField::String(log.service()));
    }
    for (key, value) in log.additional_properties() {
        fields.insert(key.as_ref(), ContentField::Value(value));
    }
    fields.insert("status", ContentField::String(log.status()));

    let mut content = Vec::new();
    content.push(b'{');
    for (index, (key, field)) in fields.into_iter().enumerate() {
        if index > 0 {
            content.push(b',');
        }
        go_json::write_string(&mut content, key);
        content.push(b':');
        match field {
            ContentField::String(value) => go_json::write_string(&mut content, value),
            ContentField::Value(value) => go_json::write_value(&mut content, value)
                .map_err(|e| generic_error!("Failed to serialize log property '{}': {}", key, e))?,
        }
    }
    content.push(b'}');

    String::from_utf8(content).map_err(|e| generic_error!("Rendered log content isn't valid UTF-8: {}", e))
}

#[cfg(test)]
mod tests {
    use std::collections::HashMap;

    use saluki_core::data_model::event::log::Log;
    use saluki_core::data_model::tags::{Tag, TagSet};
    use serde::Deserialize;
    use serde_json::{json, Value as JsonValue};
    use stringtheory::MetaString;

    use super::render_content;

    /// Vectors generated by the Go program in `testdata/generate-render-vectors`, which documents how to regenerate
    /// them.
    const RENDER_VECTORS: &str = include_str!("testdata/render_vectors.json");

    #[derive(Deserialize)]
    struct RenderVector {
        name: String,
        input: RenderInput,
        content: String,
    }

    #[derive(Deserialize)]
    struct RenderInput {
        hostname: Option<String>,
        service: Option<String>,
        message: String,
        status: String,
        properties: Option<HashMap<String, JsonValue>>,
    }

    fn log_with_properties(message: &str, properties: JsonValue) -> Log {
        let properties = match properties {
            JsonValue::Object(properties) => properties
                .into_iter()
                .map(|(key, value)| (MetaString::from(key), value))
                .collect::<HashMap<_, _>>(),
            other => panic!("properties must be a JSON object, got {}", other),
        };
        Log::new(message).with_additional_properties(properties)
    }

    #[test]
    fn matches_the_agent_byte_for_byte() {
        let vectors: Vec<RenderVector> = serde_json::from_str(RENDER_VECTORS).expect("vectors should parse");
        assert!(!vectors.is_empty());

        for vector in vectors {
            let input = vector.input;
            let properties = input
                .properties
                .unwrap_or_default()
                .into_iter()
                .map(|(key, value)| (MetaString::from(key), value))
                .collect::<HashMap<_, _>>();
            let log = Log::new(input.message)
                .with_hostname(input.hostname.map(MetaString::from))
                .with_service(input.service.map(MetaString::from))
                .with_status(input.status)
                .with_additional_properties(properties);

            let content = render_content(&log).unwrap_or_else(|e| panic!("{}: render failed: {}", vector.name, e));
            assert_eq!(content, vector.content, "{}", vector.name);
        }
    }

    #[test]
    fn properties_overwrite_top_level_fields_except_status() {
        let log = log_with_properties(
            "from body",
            json!({
                "message": "from resource",
                "hostname": "from attribute",
                "service": "from attribute",
                "status": "from resource",
                "ddtags": "from:resource",
                "datadog.log.source": "custom_source",
            }),
        )
        .with_hostname(MetaString::from_static("host-a"))
        .with_service(MetaString::from_static("svc"))
        .with_status("error");

        let content: JsonValue =
            serde_json::from_str(&render_content(&log).expect("log should render")).expect("content should be JSON");
        assert_eq!(
            content,
            json!({
                "message": "from resource",
                "hostname": "from attribute",
                "service": "from attribute",
                "status": "error",
                "ddtags": "from:resource",
                "datadog.log.source": "custom_source",
            })
        );
    }

    #[test]
    fn leaves_out_empty_hostname_and_service_but_not_status() {
        let content = render_content(&Log::new("m")).expect("log should render");
        assert_eq!(content, r#"{"message":"m","status":""}"#);
    }

    #[test]
    fn leaves_the_tags_out_of_the_content() {
        let log = Log::new("m").with_tags([Tag::from_static("env:prod")].into_iter().collect::<TagSet>());
        let content = render_content(&log).expect("log should render");
        assert_eq!(content, r#"{"message":"m","status":""}"#);
    }
}
